/**
 * リトライ設定
 *
 * 【重要】GAS には日次クォータ（UrlFetch 呼び出し回数）があるため、無限リトライは書かない。
 * 諦める条件を必ず持たせる。諦めた後は通知に回す。
 */
const RETRY_MAX_ATTEMPTS = 4;
const RETRY_BASE_MS = 1000;

/**
 * 分割実行の安全域。
 *
 * GAS の実行時間上限は6分（360秒）。ここでは 4.5分で自ら中断する。
 * 90秒の余裕を取る理由：1件の処理がリトライを挟むと最大で数十秒かかりうるため。
 * 余裕を詰めすぎると、たまに来る遅い1件で強制終了され、
 * 「どこまで処理したか」を保存する前に落ちて状態が壊れる。
 */
const MAX_RUNTIME_MS = 4.5 * 60 * 1000;
