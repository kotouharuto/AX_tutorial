/**
 * 分類カテゴリの定義。
 * これはシートではなくコードに置く。分類先が増えるとプロンプトと担当マスタの
 * 両方を直す必要があり、シートに出しても片方だけ変わって壊れるため。
 * 「シートに出すべきもの」と「出すと壊れるもの」の線引きの実例。
 */
const CATEGORIES = ['システム障害', '申請手続き', '備品・設備', 'その他'];

