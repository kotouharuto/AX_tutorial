"""長文コーパス用の埋め草。

【目的】チャンク分割を実際に発生させ、チャンク戦略の効き幅を測れるようにする。
短文コーパス（1文書＝1チャンク）では、チャンクサイズもオーバーラップも意味を持たなかった。

【設計上の制約】
**埋め草に「答えらしきもの」を入れない。** 評価問題の正解に近い記述を混ぜると、
検索が埋め草を拾って誤答し、測っているものが「チャンク戦略の効き幅」ではなく
「埋め草に引っかかるかどうか」になる。

そのため埋め草は、実務の規程に必ずある**手続き的・形式的な条文**に限定する。
（目的、適用範囲、用語定義、改廃手続き、附則、記録保存、問い合わせ窓口など）
"""

